function toDayNumber(iso: string): number {
  const [y, m, d] = iso.split('-').map(Number)
  return Date.UTC(y, m - 1, d) / 86400000
}

export function quoteOf(iso: string): Quote | null {
  if (toDayNumber(iso) > toDayNumber(EXAM_END_DATE)) return null
  const dayNumber = toDayNumber(iso) - toDayNumber(ANCHOR)
  const index = ((dayNumber % QUOTES.length) + QUOTES.length) % QUOTES.length
  return QUOTES[index]
}